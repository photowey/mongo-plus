package io.github.photowey.mongoplus.autoconfigure.core.engine;

import org.springframework.beans.BeansException;
import org.springframework.beans.factory.BeanFactory;
import org.springframework.beans.factory.BeanFactoryAware;
import org.springframework.beans.factory.config.ConfigurableListableBeanFactory;

import io.github.photowey.mongoplus.autoconfigure.core.getter.BeanFactoryGetter;

/**
 * AbstractBeanFactory - Base bean factory holder for auto-configuration components.
 *
 * @author photowey
 * @version 2026.1.0.0
 * @since 2026/03/11
 */
public abstract class AbstractBeanFactory implements BeanFactoryAware, BeanFactoryGetter {

    private ConfigurableListableBeanFactory beanFactory;

    @Override
    public void setBeanFactory(BeanFactory beanFactory) throws BeansException {
        this.beanFactory = (ConfigurableListableBeanFactory) beanFactory;
    }

    @Override
    public BeanFactory beanFactory() {
        return this.beanFactory;
    }
}
